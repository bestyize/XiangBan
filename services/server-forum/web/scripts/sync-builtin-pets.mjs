// Generate full official companion portraits with the desktop's pure SVG renderer.
// Run from any cwd: node --experimental-strip-types scripts/sync-builtin-pets.mjs
// No desktop bridge, window, account, or network code is imported into the website.
import { copyFile, mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { createHash } from 'node:crypto'
const desktop = new URL('../../../../client/xiaoban-desktop/src/', import.meta.url)
const web = new URL('../', import.meta.url)
const output = new URL('public/builtin-pets/', web)
const runtime = new URL('src/lib/builtinPetEngine/', web)
const catalog = JSON.parse(await readFile(new URL('pets/catalog.json', desktop), 'utf8'))
const modules = ['geometry.ts', 'params.ts', 'symbols.ts', 'skins.ts', 'render.ts', 'expressions.ts', 'animator.ts', 'mind.ts', 'reactions.ts']
const temporary = await mkdtemp(join(tmpdir(), 'xiaoban-pet-preview-'))
const digest = createHash('sha256')
digest.update(await readFile(new URL('pets/catalog.json', desktop)))
try {
  await mkdir(new URL('companion/', runtime), { recursive: true })
  await mkdir(new URL('pets/', runtime), { recursive: true })
  const webImports = source => source.replace(/(from\s+['"]\.[^'"]+)\.ts(['"])/g, '$1$2')
  await mkdir(join(temporary, 'companion'), { recursive: true })
  await mkdir(join(temporary, 'pets'), { recursive: true })
  await writeFile(join(temporary, 'package.json'), '{"type":"module"}')
  for (const name of modules) {
    let source = await readFile(new URL(`companion/${name}`, desktop), 'utf8')
    digest.update(source)
    if (name === 'skins.ts') {
      const flower = await readFile(new URL('companion/assets/white-flower/white_flower.webp', desktop))
      digest.update(flower)
      source = source.replace("import whiteFlower from './assets/white-flower/white_flower.webp?inline'", `const whiteFlower = 'data:image/webp;base64,${flower.toString('base64')}'`)
    }
    await writeFile(join(temporary, 'companion', name), source)
    await writeFile(new URL(`companion/${name}`, runtime), webImports(source))
  }
  for (const name of ['render.ts', 'images.ts']) {
    const source = new URL(`pets/${name}`, desktop)
    digest.update(await readFile(source))
    await copyFile(source, join(temporary, 'pets', name))
    await writeFile(new URL(`pets/${name}`, runtime), webImports(await readFile(source, 'utf8')))
  }
  await writeFile(new URL('pet.ts', runtime), webImports(await readFile(new URL('pet.ts', desktop), 'utf8')))
  const model = await readFile(new URL('pets/model.ts', desktop), 'utf8')
  await writeFile(new URL('pets/model.ts', runtime), model.slice(model.indexOf('export interface Shape'), model.indexOf('export interface PetTheme')))
  await writeFile(new URL('bridge.ts', runtime), `// Types only: no native bridge is shipped to the browser.\nexport interface Settings { size:number; expression:string; paused:boolean; fps:30|60; companionSkin:string }\n`)
  const { petMarkup } = await import(pathToFileURL(join(temporary, 'pets/render.ts')).href)
  const { stillFrame } = await import(pathToFileURL(join(temporary, 'companion/expressions.ts')).href)
  await mkdir(output, { recursive: true })
  const metadata = []
  for (const theme of catalog.themes) {
    for (const original of theme.pets) {
      const pet = structuredClone(original)
      for (const part of pet.parts) for (const shape of part.shapes) {
        if (shape.type !== 'image') continue
        if (!/^assets\/[a-z0-9-]+\.webp$/.test(shape.src)) throw new Error('Unexpected desktop pet asset path')
        const bytes = await readFile(new URL(`pets/${shape.src}`, desktop))
        digest.update(bytes)
        shape.src = `data:image/webp;base64,${bytes.toString('base64')}`
      }
      await writeFile(new URL(`${pet.id}.json`, output), JSON.stringify(pet))
      // Same full gallery viewport as the desktop: no plant/flower clipping.
      let svg = petMarkup(pet, stillFrame('happy'), `official-${pet.id}`)
      svg = svg.replace('viewBox="0 0 320 280"', 'viewBox="0 -72 320 352"')
        .replace('width="100%" height="100%"', 'width="640" height="704"')
      await writeFile(new URL(`${pet.id}.svg`, output), '<!-- Generated from client/xiaoban-desktop/src/pets and companion; run scripts/sync-builtin-pets.mjs to update. -->\n' + svg + '\n')
      metadata.push({ id:pet.id, name:pet.name, description:pet.description, kind:'pet', themeId:theme.id, themeName:theme.name, preview:`/builtin-pets/${pet.id}.svg` })
    }
  }
  const source = `// Generated from client/xiaoban-desktop/src/pets/catalog.json.\n// Complete portraits are generated by the desktop pure renderer; no native code runs here.\n// Update with: node --experimental-strip-types scripts/sync-builtin-pets.mjs\nexport interface BuiltinPet { id:string; name:string; description:string; kind:'pet'; themeId:string; themeName:string; preview:string }\nexport const BUILTIN_PET_SOURCE_SHA256 = '${digest.digest('hex')}'\nexport const BUILTIN_PETS: BuiltinPet[] = ${JSON.stringify(metadata,null,2)}\n`
  await writeFile(new URL('src/lib/builtinPets.ts', web), source)
  console.log(`Generated ${metadata.length} complete official companion previews.`)
} finally { await rm(temporary, { recursive:true, force:true }) }
