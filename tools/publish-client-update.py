#!/usr/bin/env python3
"""Publish one platform's verified update asset, then atomically advance its public feed."""
import argparse
import base64
import hashlib
import json
import os
import re
import shutil
import subprocess
import tempfile
import time
from pathlib import Path

REPO = "bestyize/XiangBan"
BRANCH = "client-updates"
ANDROID = "android-arm64-v8a"
SUFFIXES = {"windows-x86_64": ".exe", "darwin-aarch64": ".tar.gz", ANDROID: ".apk"}


def gh(*args, data=None, missing_ok=False):
    result = subprocess.run(
        ["gh", *args], input=json.dumps(data) if data is not None else None,
        capture_output=True, text=True, encoding="utf-8",
    )
    if result.returncode:
        if missing_ok and "(HTTP 404)" in result.stderr:
            return None
        raise RuntimeError(result.stderr.strip())
    return result.stdout


def api(path, method="GET", data=None, missing_ok=False):
    args = ["api", f"repos/{REPO}/{path}", "--method", method]
    if data is not None:
        args += ["--input", "-"]
    result = gh(*args, data=data, missing_ok=missing_ok)
    return json.loads(result) if result else None


def version_parts(version):
    if not re.fullmatch(r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)", version):
        raise ValueError(f"Expected a stable x.y.z version, got {version!r}")
    return tuple(map(int, version.split(".")))


def configure_desktop(args):
    key = os.environ.get("XIAOBAN_UPDATER_PUBLIC_KEY", "").strip()
    private_key = os.environ.get("TAURI_SIGNING_PRIVATE_KEY", "").strip()
    if not key and not private_key:
        print("::warning::Desktop updater signing is not configured. Building the regular installer.")
        return
    if not key or not private_key:
        raise ValueError("Set both XIAOBAN_UPDATER_PUBLIC_KEY and TAURI_SIGNING_PRIVATE_KEY")
    config = {
        "bundle": {"createUpdaterArtifacts": True},
        "plugins": {"updater": {
            "pubkey": key,
            "endpoints": [f"https://raw.githubusercontent.com/{REPO}/{BRANCH}/updates/{args.platform}.json"],
            "requireSignedVersion": True,
            "windows": {"installMode": "passive"},
        }},
    }
    args.output.write_text(json.dumps(config), encoding="utf-8")


def signature_for(package, version):
    signature = package.with_name(package.name + ".sig").read_text(encoding="utf-8").strip()
    public = os.environ["XIAOBAN_UPDATER_PUBLIC_KEY"].strip()
    key_lines = base64.b64decode(public, validate=True).decode().splitlines()
    sig_lines = base64.b64decode(signature, validate=True).decode().splitlines()
    key_id = base64.b64decode(key_lines[1], validate=True)[2:10]
    sig_key_id = base64.b64decode(sig_lines[1], validate=True)[2:10]
    if len(key_id) != 8 or key_id != sig_key_id or f"version:{version}" not in sig_lines[2].split("\t"):
        raise ValueError("Updater signature must match the configured key and release version")
    return signature


def android_metadata(package):
    tools = sorted(Path(os.environ["ANDROID_HOME"]).glob("build-tools/*/aapt"), reverse=True)
    if not tools:
        raise ValueError("Android build-tools/aapt is missing")
    aapt = tools[0]
    subprocess.run([str(aapt.with_name("apksigner")), "verify", str(package)], check=True)
    badging = subprocess.check_output([str(aapt), "dump", "badging", str(package)], text=True)
    metadata = re.search(r"^package: name='xyz\.xiangban\.xiaoban' versionCode='(\d+)' versionName='([^']+)'", badging, re.MULTILINE)
    if not metadata or "native-code: 'arm64-v8a'" not in badging.splitlines():
        raise ValueError("Expected a signed ARM64 release APK for xyz.xiangban.xiaoban")
    return metadata[2], int(metadata[1])


def ensure_feed_branch():
    ref = f"heads/{BRANCH}"
    if api(f"git/ref/{ref}", missing_ok=True):
        return
    # Keep the generated feed branch small and independent of application history.
    tree = api("git/trees", "POST", {"tree": [{
        "path": "README.md", "mode": "100644", "type": "blob",
        "content": "Official 小伴 app update manifests, generated by the manual release workflow.\n",
    }]})
    commit = api("git/commits", "POST", {
        "message": "Initialize app update feeds", "tree": tree["sha"], "parents": [],
        "author": {"name": "github-actions[bot]", "email": "41898282+github-actions[bot]@users.noreply.github.com"},
    })
    try:
        api("git/refs", "POST", {"ref": f"refs/{ref}", "sha": commit["sha"]})
    except RuntimeError:
        if not api(f"git/ref/{ref}", missing_ok=True):
            raise


def publish(args):
    if os.environ.get("GH_REPO", "").casefold() != REPO.casefold() or os.environ.get("GITHUB_REF") != "refs/heads/main":
        raise ValueError("The official feeds can only be published from the main branch of the official repository")
    tag_prefix = "xiaoban-wallpaper-v"
    if not args.tag.startswith(tag_prefix):
        raise ValueError("Expected a client release tag")
    version = args.tag.removeprefix(tag_prefix)
    version_parts(version)
    suffix = SUFFIXES[args.platform]
    packages = sorted(args.directory.glob(args.pattern))
    if len(packages) != 1 or not packages[0].name.endswith(suffix):
        raise ValueError(f"Expected exactly one {args.platform} installer, found {packages}")
    package = packages[0]
    release = json.loads(gh("release", "view", args.tag, "-R", REPO,
                            "--json", "body,isDraft,isPrerelease,publishedAt,assets"))
    if release["isDraft"] or release["isPrerelease"]:
        raise ValueError("Only public stable releases may be offered for update")
    notes = (release["body"] or "")[:4_000]
    if args.platform == ANDROID:
        version, code = android_metadata(package)
        version_parts(version)
        if not 0 < code <= 2_100_000_000:
            raise ValueError("APK versionCode is out of range")
        manifest = {"schemaVersion": 1, "version": version, "versionCode": code, "notes": notes}
        order = lambda entry: (entry["versionCode"],)
    else:
        manifest = {"version": version, "notes": notes, "pub_date": release["publishedAt"],
                    "signature": signature_for(package, version)}
        order = lambda entry: version_parts(entry["version"])

    ensure_feed_branch()
    path = f"contents/updates/{args.platform}.json"
    uploaded = False
    for attempt in range(5):
        current = api(f"{path}?ref={BRANCH}", missing_ok=True)
        if current:
            previous = json.loads(base64.b64decode(current["content"]))
            if order(previous) >= order(manifest):
                print(f"{args.platform} feed is already at v{previous['version']} or later.")
                return
        if not uploaded:
            with package.open("rb") as source:
                digest = hashlib.file_digest(source, "sha256").hexdigest()
            size = package.stat().st_size
            if not 0 < size <= 512 * 1024 * 1024:
                raise ValueError("Update package size is out of range")
            name = f"XiaoBan-Update-{args.platform}-{digest}{suffix}"
            asset = next((asset for asset in release["assets"] if asset["name"] == name), None)
            if asset is None:
                with tempfile.TemporaryDirectory() as directory:
                    upload = Path(directory) / name
                    shutil.copyfile(package, upload)
                    gh("release", "upload", args.tag, str(upload), "-R", REPO)
            elif asset["state"] != "uploaded" or asset["size"] != size:
                raise ValueError(f"Existing update asset is incomplete: {name}")
            manifest["url"] = f"https://github.com/{REPO}/releases/download/{args.tag}/{name}"
            if args.platform == ANDROID:
                manifest.update(sha256=digest, bytes=size)
            uploaded = True
        content = json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"
        body = {
            "message": f"Publish {args.platform} v{manifest['version']}",
            "branch": BRANCH,
            "content": base64.b64encode(content.encode()).decode(),
        }
        if current:
            body["sha"] = current["sha"]
        try:
            api(path, "PUT", body)
            return
        except RuntimeError as error:
            if attempt == 4 or not any(f"(HTTP {code})" in str(error) for code in (409, 422)):
                raise
            time.sleep(attempt + 1)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(required=True)
    configure = subparsers.add_parser("configure-desktop")
    configure.add_argument("platform", choices=[p for p in SUFFIXES if p != ANDROID])
    configure.add_argument("output", type=Path)
    configure.set_defaults(run=configure_desktop)
    publisher = subparsers.add_parser("publish")
    publisher.add_argument("platform", choices=SUFFIXES)
    publisher.add_argument("tag")
    publisher.add_argument("directory", type=Path)
    publisher.add_argument("pattern")
    publisher.set_defaults(run=publish)
    parsed = parser.parse_args()
    parsed.run(parsed)
