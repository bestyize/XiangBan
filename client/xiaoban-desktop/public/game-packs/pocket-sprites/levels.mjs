// Row-major on a square grid. A dot is a hole, # is playable, i/I are ice, and h is honey.
function level({ opening, shape = opening, specials = {}, ...data }) {
  const size = shape.length
  if ((size !== 8 && size !== 9) || shape.some(row => row.length !== size) ||
      (opening && (opening.length !== size || opening.some(row => row.length !== size)))) {
    throw new Error(`Level ${data.id} must use an 8×8 or 9×9 square layout`)
  }
  const cells = Array.from(shape.join(''))
  return {
    ...data,
    size,
    mask: cells.map(cell => cell !== '.'),
    ice: cells.map(cell => cell === 'I' ? 2 : Number(cell === 'i')),
    honey: cells.map(cell => Number(cell === 'h')),
    ...(opening && {
      initialBoard: Array.from(opening.join(''), (cell, index) => {
        if (cell === '.') return null
        const color = Number(cell)
        const special = specials[index]
        return special ? { color, special } : color
      }),
    }),
  }
}

