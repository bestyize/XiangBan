#!/usr/bin/env python3
"""Refresh the mobile-owned navigation snapshot from the reviewed forum catalog. No network."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[3]
catalog = json.loads((root / 'services/server-forum/editorial/navigation.json').read_text())
output = root / 'client/xiaoban-multiplatform/common/community-core/src/commonMain/kotlin/xyz/xiangban/xiaoban/common/community/NavigationCatalog.kt'
def quote(value):
    return json.dumps(value, ensure_ascii=False).replace('$', '${\'$\'}')
lines = ['// Generated by tools/sync-navigation-catalog.py. Reviewed catalog: 2026-11-03.',
         'package xyz.xiangban.xiaoban.common.community', '',
         'internal val bundledNavigation = NavigationSnapshot(', f'    version = {catalog["version"]},', '    categories = listOf(']
for item in catalog['categories']:
    filters = ', '.join('NavigationFilter(%s, %s)' % (quote(f['key']), quote(f['label'])) for f in item['filters'])
    lines.append('        NavigationCategory(%s, %s, listOf(%s)),' % (quote(item['key']), quote(item['label']), filters))
lines += ['    ),', '    items = listOf(']
for item in catalog['items']:
    fields = ', '.join(f'{key} = {quote(item[key])}' for key in ['key', 'group', 'name', 'vendor', 'url', 'category', 'subtype', 'region', 'summary', 'logo'])
    lines.append(f'        NavLink({fields}),')
lines += ['    ),', '    legacy = mapOf(']
for key, value in catalog['legacy_items'].items():
    lines.append('        %s to NavigationLegacy(%s, %s, %s),' % (quote(key), quote(value['name']), quote(value['vendor']), quote(value['url'])))
lines += ['    ),', ')', '']
output.write_text('\n'.join(lines))
print(f'Synced {len(catalog["items"])} navigation entries')
