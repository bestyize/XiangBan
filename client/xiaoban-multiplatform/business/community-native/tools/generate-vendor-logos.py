#!/usr/bin/env python3
"""Generate Compose vectors from pinned local brand assets, without network or dependencies."""
from pathlib import Path
import json
import xml.etree.ElementTree as ET
base = Path(__file__).resolve().parents[1]
assets = base / 'assets/vendor-logos'
manifest = json.loads((assets / 'manifest.json').read_text())
output = base / 'src/commonMain/kotlin/xyz/xiangban/xiaoban/business/communitynative/VendorBrandLogos.kt'
lines = ['// Generated by tools/generate-vendor-logos.py; sources/license: assets/vendor-logos/.',
 'package xyz.xiangban.xiaoban.business.communitynative', '',
 'import androidx.compose.ui.graphics.Color', 'import androidx.compose.ui.graphics.PathFillType',
 'import androidx.compose.ui.graphics.SolidColor', 'import androidx.compose.ui.graphics.vector.ImageVector',
 'import androidx.compose.ui.graphics.vector.addPathNodes', 'import androidx.compose.ui.unit.dp', '',
 'internal object VendorBrandLogos {']
seen = set()
for vendor in manifest['vendors']:
 root = ET.parse(assets / vendor['file']).getroot()
 x, y, w, h = map(float, root.attrib['viewBox'].split())
 assert x == y == 0
 paths = []
 for node in root.iter():
  tag = node.tag.rsplit('}', 1)[-1]
  assert tag in ('svg', 'title', 'path'), f'Unsupported SVG element: {tag}'
  assert not any(k in node.attrib for k in ('transform', 'mask', 'clip-path'))
  if tag == 'path':
   assert node.get('d')
   rule = node.get('fill-rule', root.get('fill-rule', 'nonzero'))
   alpha = str(float(node.get('fill-opacity', 1)))+'f'
   paths.append('            .addPath(pathData = addPathNodes(' + json.dumps(node.get('d')) + '), fill = SolidColor(Color.Black), fillAlpha = '+alpha+', pathFillType = PathFillType.'+('EvenOdd' if rule == 'evenodd' else 'NonZero') + ')')
 lines += [f'    private val {vendor["id"]} by lazy {{', f'        val color = Color(0xFF{vendor["color"]})',
 f'        BrandLogo(color, color.copy(alpha = 0.1f), ImageVector.Builder(name = "{vendor["id"]}", defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = {w:.1f}f, viewportHeight = {h:.1f}f)',
 *paths, '            .build())', '    }']
lines += ['', '    fun find(name: String): BrandLogo? = when (name.substringBefore(\'/\').lowercase().filter { it.isLetterOrDigit() }) {']
for vendor in manifest['vendors']:
 aliases = sorted(set(''.join(c for c in a.lower() if c.isalnum()) for a in vendor['aliases']))
 assert not seen.intersection(aliases), 'Duplicate vendor alias'
 seen.update(aliases)
 lines += ['        ' + ', '.join(json.dumps(a, ensure_ascii=False) for a in aliases) + ' -> ' + vendor['id']]
lines += ['        else -> null', '    }', '}', '']
output.write_text('\n'.join(lines))
print(f'Generated {len(manifest["vendors"])} marks / {len(seen)} aliases')
