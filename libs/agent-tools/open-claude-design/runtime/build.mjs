import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
const result=await build({entryPoints:['react-bridge.js'],bundle:true,minify:true,format:'iife',platform:'browser',target:['safari15','chrome100'],define:{'process.env.NODE_ENV':'"production"'},outfile:'vendor/react-bridge.js',legalComments:'eof',metafile:true});
// Keep the licenses of packages actually included in the distributable.
const packages=[...new Set(Object.keys(result.metafile.inputs).filter(p=>p.startsWith('node_modules/')).map(p=>p.split('/').slice(1,p.split('/')[1].startsWith('@')?3:2).join('/')))];
let notices='Generated by npm run build. Source dependencies are pinned in package-lock.json.\n';
for(const name of packages.sort()){
 let license;for(const file of ['LICENSE','LICENSE.md','LICENSE.txt','license']){try{license=await readFile(`node_modules/${name}/${file}`,'utf8');break;}catch{}}
 if(!license)throw Error(`Missing license for ${name}`);
 notices+=`\n--- ${name} ---\n${license}\n`;
}
await writeFile('vendor/LICENSES.txt',notices);
