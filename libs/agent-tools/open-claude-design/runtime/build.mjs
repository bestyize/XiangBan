import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
const result=await build({entryPoints:['react-bridge.js','capture.js'],bundle:true,minify:true,format:'iife',platform:'browser',target:['safari15','chrome100'],define:{'process.env.NODE_ENV':'"production"'},outdir:'vendor',legalComments:'eof',metafile:true,plugins:[{
 name:'offscreen-capture-image',setup(build){build.onLoad({filter:/html-to-image\/es\/util\.js$/},async({path})=>{
  const contents=await readFile(path,'utf8'),before='requestAnimationFrame(() => resolve(img));';
  if(!contents.includes(before))throw Error('Review html-to-image image decoding after dependency upgrade');
  // Decoded SVG images can be drawn immediately; offscreen sandbox frames do not receive rAF.
  return {contents:contents.replace(before,'setTimeout(() => resolve(img), 0);'),loader:'js'};
 });}
}]});
// Keep the licenses of packages actually included in the distributable.
const packages=[...new Set(Object.keys(result.metafile.inputs).filter(p=>p.startsWith('node_modules/')).map(p=>p.split('/').slice(1,p.split('/')[1].startsWith('@')?3:2).join('/')))];
let notices='Generated by npm run build. Source dependencies are pinned in package-lock.json.\n';
for(const name of packages.sort()){
 let license;for(const file of ['LICENSE','LICENSE.md','LICENSE.txt','license']){try{license=await readFile(`node_modules/${name}/${file}`,'utf8');break;}catch{}}
 if(!license)throw Error(`Missing license for ${name}`);
 notices+=`\n--- ${name} ---\n${license}\n`;
}
await writeFile('vendor/LICENSES.txt',notices);
